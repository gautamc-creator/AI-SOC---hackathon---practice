#!/usr/bin/env python3
"""Comparative evaluation: Elastic rules alone vs Attack Discovery alone vs Attack Discovery + VIGIL.

Runs all eight ``eval/scenarios.py`` fixtures through three conditions and
records, per scenario: evidence-field completeness, correct exposure/accounts,
CERT-In field population, human-escalation accuracy, local runtime, and
reliability across repeated deterministic runs.

Honesty boundary: the AI-narrative-dependent sub-metrics (unsupported-claims
count, generation tokens/latency) are REAL only for scenario m1, which has an
actual captured Attack Discovery run in artifacts/attack-discovery-baseline.json.
For the other seven scenarios those cells are marked NOT_YET_CAPTURED — this
harness does not fabricate LLM output. See docs/EVAL-LIVE-CAPTURE.md for the
exact steps to fill them in against a live Elastic + Bedrock/LLM connector.
"""
from __future__ import annotations

import json
import re
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "eval"))
sys.path.insert(0, str(ROOT))

from scenarios import load_all  # noqa: E402
from rules_only import evaluate as evaluate_rules  # noqa: E402
from vigil_layer import run_once, score_against_ground_truth  # noqa: E402
from workflow.review_discovery import RISKY_CLAIMS  # noqa: E402

RELIABILITY_RUNS = 20


def claim_review_text(text: str) -> list[str]:
    findings = []
    for phrase in RISKY_CLAIMS:
        if re.search(rf"\b{re.escape(phrase)}\b", text, flags=re.IGNORECASE):
            findings.append(phrase)
    return findings


def load_real_ad_capture() -> dict | None:
    path = ROOT / "artifacts/attack-discovery-baseline.json"
    if not path.exists():
        return None
    payload = json.loads(path.read_text(encoding="utf-8"))
    discoveries = payload.get("response", {}).get("data", [])
    if not discoveries:
        return None
    d = discoveries[0]
    text = "\n".join(str(d.get(f, "")) for f in ("title", "summary_markdown", "details_markdown", "entity_summary_markdown"))
    return {
        "connector_id": payload.get("response", {}).get("generation", {}).get("connector_id"),
        "duration_ms": round(payload["response"]["generation"].get("average_successful_duration_nanoseconds", 0) / 1e6, 1),
        "unsupported_claims": claim_review_text(text),
        "text": text,
    }


def naive_escalation_correct(escalated: bool, expected_decision: str) -> tuple[bool, str]:
    """Score a binary escalate/don't-escalate baseline against a three-way expected verdict.

    A rules-alone or Attack-Discovery-alone baseline has no way to express "hold for
    human review, evidence is incomplete" — it can only escalate or not. When the
    correct verdict genuinely is HOLD, either binary answer is a category error, so
    this is always scored incorrect for that case, with the reason recorded.
    """
    if expected_decision == "HOLD_INSUFFICIENT_CHAIN":
        return False, "Binary baseline cannot express a hold-for-review verdict; scored incorrect regardless of which way it lands."
    expected_escalate = expected_decision == "REPORTABLE"
    return escalated == expected_escalate, "matches expected escalate/don't-escalate call" if escalated == expected_escalate else "wrong binary call"


def evaluate_scenario(scenario: dict, real_ad: dict | None) -> dict:
    t0 = time.perf_counter()
    rules_result = evaluate_rules(scenario["events"])
    rules_ms = (time.perf_counter() - t0) * 1000
    rules_correct, rules_reason = naive_escalation_correct(rules_result["naive_escalation_recommended"], scenario["expected_decision"])
    rules_condition = {
        "condition": "rules_alone",
        "final_alert_count": rules_result["final_alert_count"],
        "naive_escalation_recommended": rules_result["naive_escalation_recommended"],
        "escalation_correct": rules_correct, "escalation_reason": rules_reason,
        "failure_class": "none" if rules_correct else ("detection_coverage_gap" if scenario.get("known_detection_gap") else "binary_baseline_limit"),
        "exposure_provided": False, "accounts_provided": False, "cert_in_fields_populated_pct": 0.0,
        "unsupported_claims": "NOT_APPLICABLE — no narrative is generated by rules alone.",
        "runtime_ms": round(rules_ms, 3),
    }

    ad_correct, ad_reason = naive_escalation_correct(rules_result["any_rule_fired"], scenario["expected_decision"])
    if scenario.get("real_ad_capture_available") and real_ad:
        ad_condition = {
            "condition": "attack_discovery_alone", "status": "REAL_CAPTURE",
            "connector": real_ad["connector_id"], "generation_duration_ms": real_ad["duration_ms"],
            "naive_escalation_recommended": rules_result["any_rule_fired"],
            "escalation_correct": ad_correct, "escalation_reason": ad_reason,
            "exposure_provided": False, "accounts_provided": False, "cert_in_fields_populated_pct": 0.0,
            "unsupported_claims_count": len(real_ad["unsupported_claims"]),
            "unsupported_claims": real_ad["unsupported_claims"],
        }
    else:
        ad_condition = {
            "condition": "attack_discovery_alone", "status": "NOT_YET_CAPTURED",
            "note": "Requires seeding this scenario into an isolated live index and running Attack Discovery for "
                    "real; see docs/EVAL-LIVE-CAPTURE.md. Structural facts below hold regardless of the specific "
                    "LLM/connector, since Attack Discovery has no bank-context join or regulatory-field template.",
            "naive_escalation_recommended": "NOT_YET_CAPTURED",
            "escalation_correct": "NOT_YET_CAPTURED",
            "escalation_reason": "No Attack Discovery output exists for this scenario; it is not scored.",
            "exposure_provided": False, "accounts_provided": False, "cert_in_fields_populated_pct": 0.0,
            "unsupported_claims_count": "NOT_YET_CAPTURED",
        }

    t0 = time.perf_counter()
    hashes = set()
    last_result = None
    for _ in range(RELIABILITY_RUNS):
        last_result = run_once(scenario)
        hashes.add(last_result["result_hash"])
    vigil_ms = (time.perf_counter() - t0) * 1000 / RELIABILITY_RUNS
    scoring = score_against_ground_truth(scenario, last_result)
    vigil_condition = {
        "condition": "attack_discovery_plus_vigil",
        "final_alert_count": last_result["rules"]["final_alert_count"],
        "escalation_decision": last_result["escalation"]["decision"],
        "escalation_reason": last_result["escalation"]["reason"],
        "escalation_correct": scoring["escalation_correct"], "failure_class": scoring["failure_class"],
        "exposure": last_result["exposure"], "exposure_correct": scoring["exposure_correct"],
        "exposure_note": scoring["exposure_note"],
        "accounts": last_result["accounts"], "accounts_correct": scoring["accounts_correct"],
        "cert_in_fields_populated_pct": last_result["cert_in_completeness"]["completeness_pct"],
        "unsupported_claims": (real_ad["unsupported_claims"] if scenario.get("real_ad_capture_available") and real_ad
                                else "NOT_YET_CAPTURED — narrative not generated for this scenario"),
        "reliability": f"{len(hashes)}/1 distinct outputs across {RELIABILITY_RUNS} runs (1 = fully reproducible)",
        "runtime_ms": round(vigil_ms, 3),
    }

    return {
        "scenario_id": scenario["id"], "category": scenario["category"], "narrative": scenario["narrative"],
        "ground_truth": {"reportable": scenario["reportable"], "expected_exposure_inr": scenario["expected_exposure_inr"],
                          "expected_accounts": scenario["expected_accounts"], "exposure_computable": scenario["exposure_computable"]},
        "rules_alone": rules_condition, "attack_discovery_alone": ad_condition, "attack_discovery_plus_vigil": vigil_condition,
    }


def to_markdown(results: list[dict]) -> str:
    lines = [
        "# VIGIL comparative evaluation results",
        "",
        "Generated by `eval/run_comparison.py`. The candidate rule set and deterministic VIGIL grounding/decision layer "
        "are REAL, locally computed results (100% reproducible, see `reliability`). Attack-Discovery-alone "
        "narrative metrics are REAL only for `m1_credential_theft_to_bulk_upi` (one captured live run); every "
        "other scenario's narrative-dependent cell is explicitly marked NOT_YET_CAPTURED — see "
        "`docs/EVAL-LIVE-CAPTURE.md` to fill those in live.",
        "",
        "| Scenario | Category | Rules-alone escalates correctly? | AD-alone escalates correctly? | VIGIL decision | VIGIL escalation correct? | VIGIL exposure correct? | CERT-In fields populated |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        lines.append(
            f"| {r['scenario_id']} | {r['category']} | {r['rules_alone']['escalation_correct']} | "
            f"{r['attack_discovery_alone']['escalation_correct']} | {r['attack_discovery_plus_vigil']['escalation_decision']} | "
            f"{r['attack_discovery_plus_vigil']['escalation_correct']} | {r['attack_discovery_plus_vigil']['exposure_correct']} | "
            f"{r['attack_discovery_plus_vigil']['cert_in_fields_populated_pct']}% |"
        )
    naive_wrong = [r for r in results if not r["rules_alone"]["escalation_correct"]]
    vigil_wrong = [r for r in results if not r["attack_discovery_plus_vigil"]["escalation_correct"]]
    detection_gaps = [r for r in results if r["attack_discovery_plus_vigil"]["failure_class"] == "detection_coverage_gap"]
    grounding_errors = [r for r in results if r["attack_discovery_plus_vigil"]["failure_class"] == "grounding_error"]
    binary_limited = [r for r in naive_wrong if r["rules_alone"]["failure_class"] == "binary_baseline_limit"]
    lines += [
        "",
        "## Honest breakdown (not a single pass/fail score)",
        "",
        f"- Naive rules-alone escalation is wrong on {len(naive_wrong)}/{len(results)} scenarios: "
        f"{len(binary_limited)} of those are cases where a binary escalate/don't-escalate baseline structurally "
        f"cannot express the correct 'hold for review' verdict, and the rest are false positives on "
        f"authorized/benign traffic.",
        f"- VIGIL's grounded decision layer is wrong on {len(vigil_wrong)}/{len(results)} scenarios, of which "
        f"{len(detection_gaps)} are **upstream detection-coverage gaps** in the candidate local rule set and "
        f"{len(grounding_errors)} are genuine grounding/decision-layer errors.",
        "- Candidate rules 06 and 07 are represented by faithful local predicates and disabled Elastic definitions; "
        "their m2/m3 results are not live Elastic proof until the rules are replayed in the isolated evaluation index.",
    ]
    if detection_gaps:
        lines.append(f"  - Coverage gaps found: {', '.join(r['scenario_id'] for r in detection_gaps)} — "
                      f"these need a new detection rule, not a VIGIL fix. See docs/EVAL-LIVE-CAPTURE.md.")
    if grounding_errors:
        lines.append(f"  - Genuine grounding errors: {', '.join(r['scenario_id'] for r in grounding_errors)}.")
    exposure_notes = [r for r in results if r["attack_discovery_plus_vigil"].get("exposure_note")]
    if exposure_notes:
        lines.append("")
        lines.append("## Exposure-formula gaps found by this harness")
        lines.append("")
        for r in exposure_notes:
            lines.append(f"- **{r['scenario_id']}**: {r['attack_discovery_plus_vigil']['exposure_note']}")
    lines += [
        "",
        "This is a rehearsal-scale comparison against eight labelled fixtures, not a statistically powered study.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    scenarios = load_all()
    real_ad = load_real_ad_capture()
    results = [evaluate_scenario(s, real_ad) for s in scenarios]
    out_dir = ROOT / "artifacts/eval"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "comparison-results.json").write_text(json.dumps(results, indent=2, default=str) + "\n", encoding="utf-8")
    (out_dir / "COMPARISON-RESULTS.md").write_text(to_markdown(results), encoding="utf-8")
    print(f"Evaluated {len(results)} scenarios. Wrote artifacts/eval/comparison-results.json and COMPARISON-RESULTS.md.")
    for r in results:
        print(f"  {r['scenario_id']:45s} rules_ok={r['rules_alone']['escalation_correct']!s:5s} "
              f"vigil_ok={r['attack_discovery_plus_vigil']['escalation_correct']!s:5s} "
              f"decision={r['attack_discovery_plus_vigil']['escalation_decision']}")


if __name__ == "__main__":
    main()
